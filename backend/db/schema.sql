-- =====================================================================
--  Tildes — схема базы данных для PostgreSQL 16 (23 таблицы)
--
--  Справочный DDL, повторяющий Django-модели (backend/learning/models.py).
--  В проекте таблицы создаются миграциями: python manage.py migrate.
--  Этот файл — для просмотра схемы, ревью и ручного развёртывания:
--      psql -d tildes -f schema.sql
--
--  Группы: пользователи · контент · админка · прогресс ученика.
--  Зарезервированы на будущее (не создаются): listening_tasks, speaking_tasks, writing_tasks.
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
--  Пользователи и контент
-- ---------------------------------------------------------------------

CREATE TABLE levels (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(4)   NOT NULL UNIQUE,                 -- A1 … C1
    title_kz      varchar(120) NOT NULL,
    title_ru      varchar(120) NOT NULL,
    description   text         NOT NULL DEFAULT '',
    sort_order    smallint     NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    is_published  boolean      NOT NULL DEFAULT false,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now()
);

CREATE TABLE users (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             varchar(254) NOT NULL UNIQUE,
    password          varchar(128) NOT NULL,
    display_name      varchar(80)  NOT NULL DEFAULT '',
    role              varchar(10)  NOT NULL DEFAULT 'student'
                      CHECK (role IN ('student', 'editor', 'admin')),
    current_level_id  bigint       REFERENCES levels (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    points            integer      NOT NULL DEFAULT 0 CHECK (points >= 0),
    is_active         boolean      NOT NULL DEFAULT true,
    is_superuser      boolean      NOT NULL DEFAULT false,
    date_joined       timestamptz  NOT NULL DEFAULT now(),
    last_login        timestamptz
);
CREATE INDEX users_current_level_idx ON users (current_level_id);
CREATE INDEX users_points_idx        ON users (points);

CREATE TABLE media_files (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          varchar(10)  NOT NULL CHECK (kind IN ('image', 'audio', 'video')),
    file          varchar(255) NOT NULL,                        -- путь относительно MEDIA_ROOT
    mime_type     varchar(100) NOT NULL DEFAULT '',
    size_bytes    integer      NOT NULL DEFAULT 0 CHECK (size_bytes >= 0),
    duration_sec  numeric(8,2),
    uploaded_by   bigint       REFERENCES users (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    created_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX media_files_uploaded_by_idx ON media_files (uploaded_by);

CREATE TABLE modules (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    level_id      bigint       NOT NULL REFERENCES levels (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    number        smallint     NOT NULL CHECK (number >= 0),
    title_kz      varchar(200) NOT NULL,
    title_ru      varchar(200) NOT NULL,
    emoji         varchar(8)   NOT NULL DEFAULT '',
    color         varchar(7)   NOT NULL DEFAULT '#8B5CF6',      -- #RRGGBB
    sort_order    smallint     NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    status        varchar(10)  NOT NULL DEFAULT 'draft'
                  CHECK (status IN ('draft', 'review', 'published', 'archived')),
    created_by    bigint       REFERENCES users (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now(),
    published_at  timestamptz,
    CONSTRAINT modules_level_number_uniq UNIQUE (level_id, number)
);
CREATE INDEX modules_status_idx     ON modules (status);
CREATE INDEX modules_created_by_idx ON modules (created_by);

CREATE TABLE lessons (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id     bigint       NOT NULL REFERENCES modules (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    code          varchar(4)   NOT NULL,                        -- «1.1», «10.4»
    title_kz      varchar(200) NOT NULL,
    title_ru      varchar(200) NOT NULL DEFAULT '',
    sort_order    smallint     NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    status        varchar(10)  NOT NULL DEFAULT 'draft'
                  CHECK (status IN ('draft', 'review', 'published', 'archived')),
    created_by    bigint       REFERENCES users (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    updated_by    bigint       REFERENCES users (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now(),
    published_at  timestamptz,
    CONSTRAINT lessons_module_code_uniq UNIQUE (module_id, code)
);
CREATE INDEX lessons_status_idx ON lessons (status);

CREATE TABLE lesson_blocks (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id   bigint      NOT NULL REFERENCES lessons (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    block_type  varchar(12) NOT NULL CHECK (block_type IN ('words', 'cards', 'grammar', 'text', 'quiz')),
    sort_order  smallint    NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    is_enabled  boolean     NOT NULL DEFAULT true,
    CONSTRAINT lesson_blocks_lesson_type_uniq UNIQUE (lesson_id, block_type)
);

CREATE TABLE words (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id       bigint       NOT NULL REFERENCES lessons (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    kz              varchar(200) NOT NULL,
    ru              varchar(300) NOT NULL,
    transcription   varchar(200) NOT NULL DEFAULT '',
    part_of_speech  varchar(30)  NOT NULL DEFAULT '',
    example_kz      text         NOT NULL DEFAULT '',
    example_ru      text         NOT NULL DEFAULT '',
    image_id        bigint       REFERENCES media_files (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    audio_id        bigint       REFERENCES media_files (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    sort_order      smallint     NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    status          varchar(10)  NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft', 'review', 'published', 'archived')),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX words_lesson_idx ON words (lesson_id, sort_order);
CREATE INDEX words_status_idx ON words (status);

CREATE TABLE texts (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id       bigint       NOT NULL REFERENCES lessons (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    title           varchar(200) NOT NULL,
    body            text         NOT NULL,                      -- абзацы через пустую строку
    translation_ru  text         NOT NULL DEFAULT '',
    audio_id        bigint       REFERENCES media_files (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    status          varchar(10)  NOT NULL DEFAULT 'draft'
                    CHECK (status IN ('draft', 'review', 'published', 'archived')),
    created_at      timestamptz  NOT NULL DEFAULT now(),
    updated_at      timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX texts_lesson_idx ON texts (lesson_id);

CREATE TABLE grammar_rules (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id    bigint       NOT NULL REFERENCES lessons (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    title_kz     varchar(200) NOT NULL,
    title_ru     varchar(200) NOT NULL,
    explanation  text         NOT NULL DEFAULT '',
    sort_order   smallint     NOT NULL DEFAULT 0 CHECK (sort_order >= 0),
    status       varchar(10)  NOT NULL DEFAULT 'draft'
                 CHECK (status IN ('draft', 'review', 'published', 'archived')),
    created_at   timestamptz  NOT NULL DEFAULT now(),
    updated_at   timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX grammar_rules_lesson_idx ON grammar_rules (lesson_id);

CREATE TABLE grammar_table_rows (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id     bigint       NOT NULL REFERENCES grammar_rules (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    form_label  varchar(100) NOT NULL DEFAULT '',
    pattern     varchar(300) NOT NULL DEFAULT '',
    example     varchar(300) NOT NULL DEFAULT '',
    sort_order  smallint     NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);
CREATE INDEX grammar_table_rows_rule_idx ON grammar_table_rows (rule_id);

CREATE TABLE grammar_examples (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id     bigint   NOT NULL REFERENCES grammar_rules (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    text_kz     text     NOT NULL,
    text_ru     text     NOT NULL DEFAULT '',
    sort_order  smallint NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);
CREATE INDEX grammar_examples_rule_idx ON grammar_examples (rule_id);

CREATE TABLE quizzes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id   bigint       NOT NULL REFERENCES lessons (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    title       varchar(200) NOT NULL,
    status      varchar(10)  NOT NULL DEFAULT 'draft'
                CHECK (status IN ('draft', 'review', 'published', 'archived')),
    created_at  timestamptz  NOT NULL DEFAULT now(),
    updated_at  timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX quizzes_lesson_idx ON quizzes (lesson_id);

CREATE TABLE quiz_questions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id        bigint      NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    question_type  varchar(10) NOT NULL DEFAULT 'single' CHECK (question_type IN ('single', 'multiple', 'text')),
    prompt         text        NOT NULL,
    explanation    text        NOT NULL DEFAULT '',
    sort_order     smallint    NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);
CREATE INDEX quiz_questions_quiz_idx ON quiz_questions (quiz_id, sort_order);

CREATE TABLE quiz_options (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id  bigint       NOT NULL REFERENCES quiz_questions (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    text         varchar(300) NOT NULL,
    is_correct   boolean      NOT NULL DEFAULT false,
    sort_order   smallint     NOT NULL DEFAULT 0 CHECK (sort_order >= 0)
);
CREATE INDEX quiz_options_question_idx ON quiz_options (question_id, sort_order);

-- ---------------------------------------------------------------------
--  Админка
-- ---------------------------------------------------------------------

CREATE TABLE audit_log (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id     bigint      REFERENCES users (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    action       varchar(10) NOT NULL CHECK (action IN ('create', 'update', 'delete', 'publish')),
    entity_type  varchar(30) NOT NULL,                          -- имя таблицы: words, lessons, …
    entity_id    bigint,
    changes      jsonb       NOT NULL DEFAULT '{}'::jsonb,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_entity_idx     ON audit_log (entity_type, entity_id);
CREATE INDEX audit_log_created_at_idx ON audit_log (created_at);
CREATE INDEX audit_log_actor_idx      ON audit_log (actor_id);

-- ---------------------------------------------------------------------
--  Прогресс ученика
-- ---------------------------------------------------------------------

CREATE TABLE point_transactions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    amount       integer     NOT NULL,
    reason       varchar(16) NOT NULL
                 CHECK (reason IN ('card_learned', 'card_again', 'topic_first', 'topic_repeat', 'quiz', 'admin')),
    source_type  varchar(20) NOT NULL DEFAULT '',               -- card_answer, card_session, quiz_attempt
    source_id    bigint,
    created_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX point_transactions_user_idx       ON point_transactions (user_id);
CREATE INDEX point_transactions_created_at_idx ON point_transactions (created_at);

CREATE TABLE user_activity_days (
    id       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id  bigint NOT NULL REFERENCES users (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    day      date   NOT NULL,
    CONSTRAINT user_activity_days_uniq UNIQUE (user_id, day)
);

CREATE TABLE user_word_progress (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint     NOT NULL REFERENCES users (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    word_id        bigint     NOT NULL REFERENCES words (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    learned_count  integer    NOT NULL DEFAULT 0 CHECK (learned_count >= 0),
    again_count    integer    NOT NULL DEFAULT 0 CHECK (again_count >= 0),
    last_result    varchar(8) NOT NULL DEFAULT '' CHECK (last_result IN ('', 'learned', 'again')),
    last_seen_at   timestamptz,
    CONSTRAINT user_word_progress_uniq UNIQUE (user_id, word_id)
);
CREATE INDEX user_word_progress_word_idx ON user_word_progress (word_id);

CREATE TABLE user_lesson_progress (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    lesson_id           bigint      NOT NULL REFERENCES lessons (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    words_read          boolean     NOT NULL DEFAULT false,
    grammar_read        boolean     NOT NULL DEFAULT false,
    text_read           boolean     NOT NULL DEFAULT false,
    cards_completions   integer     NOT NULL DEFAULT 0 CHECK (cards_completions >= 0),
    quiz_best           smallint    NOT NULL DEFAULT 0 CHECK (quiz_best >= 0),
    first_completed_at  timestamptz,
    updated_at          timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT user_lesson_progress_uniq UNIQUE (user_id, lesson_id)
);
CREATE INDEX user_lesson_progress_lesson_idx ON user_lesson_progress (lesson_id);

CREATE TABLE card_sessions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    mode           varchar(8)  NOT NULL DEFAULT 'topic' CHECK (mode IN ('topic', 'review')),
    module_id      bigint      REFERENCES modules (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    lesson_id      bigint      REFERENCES lessons (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    cards_total    smallint    NOT NULL DEFAULT 0 CHECK (cards_total >= 0),
    learned_count  smallint    NOT NULL DEFAULT 0 CHECK (learned_count >= 0),
    again_count    smallint    NOT NULL DEFAULT 0 CHECK (again_count >= 0),
    points_earned  integer     NOT NULL DEFAULT 0,
    started_at     timestamptz NOT NULL DEFAULT now(),
    finished_at    timestamptz
);
CREATE INDEX card_sessions_user_open_idx ON card_sessions (user_id, finished_at);
CREATE INDEX card_sessions_module_idx    ON card_sessions (module_id);
CREATE INDEX card_sessions_lesson_idx    ON card_sessions (lesson_id);

CREATE TABLE card_answers (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id   bigint      NOT NULL REFERENCES card_sessions (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    word_id      bigint      NOT NULL REFERENCES words (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    result       varchar(8)  NOT NULL CHECK (result IN ('learned', 'again')),
    answered_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX card_answers_session_idx ON card_answers (session_id);
CREATE INDEX card_answers_word_idx    ON card_answers (word_id);

CREATE TABLE quiz_attempts (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    quiz_id        bigint      NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    correct_count  smallint    NOT NULL DEFAULT 0 CHECK (correct_count >= 0),
    total_count    smallint    NOT NULL DEFAULT 0 CHECK (total_count >= 0),
    points_earned  integer     NOT NULL DEFAULT 0,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX quiz_attempts_user_idx ON quiz_attempts (user_id);
CREATE INDEX quiz_attempts_quiz_idx ON quiz_attempts (quiz_id);

CREATE TABLE quiz_attempt_answers (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    attempt_id   bigint       NOT NULL REFERENCES quiz_attempts (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    question_id  bigint       NOT NULL REFERENCES quiz_questions (id) ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED,
    option_id    bigint       REFERENCES quiz_options (id) ON DELETE SET NULL DEFERRABLE INITIALLY DEFERRED,
    text_answer  varchar(300) NOT NULL DEFAULT '',
    is_correct   boolean      NOT NULL DEFAULT false,
    CONSTRAINT quiz_attempt_answers_uniq UNIQUE (attempt_id, question_id)
);
CREATE INDEX quiz_attempt_answers_question_idx ON quiz_attempt_answers (question_id);
CREATE INDEX quiz_attempt_answers_option_idx   ON quiz_attempt_answers (option_id);

-- ---------------------------------------------------------------------
